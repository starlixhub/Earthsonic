"""
backend/routes/sonification.py
Flask REST API Endpoints for STRAUSS Audio Sonification.
NASA Space Apps Challenge 2026: "The Earth Information Jukebox"

Serves:
  - GET /api/sonify/<dataset_id>
  - GET /api/sonify/orchestra
  - GET /api/sonify/differential
  - GET /api/sonification/explanations
  - GET /api/sonification/metadata
"""

import re
from typing import Tuple, Optional
from flask import Blueprint, jsonify, request, send_file

from backend.sonification.engine import default_engine
from backend.sonification.mappings import SONIFICATION_EXPLANATIONS

sonification_bp = Blueprint("sonification", __name__, url_prefix="/api")

DATE_REGEX = re.compile(r"^\d{4}(?:-(?:0[1-9]|1[0-2]))?$")


def _parse_period_string(period_str: str) -> Tuple[Optional[str], Optional[str]]:
    """Parse comma-separated or single date period string into (start, end)."""
    if not period_str:
        return None, None
    parts = [p.strip() for p in period_str.split(",") if p.strip()]
    if len(parts) >= 2:
        return parts[0], parts[1]
    elif len(parts) == 1:
        return parts[0], parts[0]
    return None, None


@sonification_bp.route("/sonify/<dataset_id>", methods=["GET"])
def sonify_dataset_endpoint(dataset_id: str):
    """
    Stream 44.1 kHz stereo WAV file generated by STRAUSS for a specified NASA dataset.
    Query parameters:
      - start: YYYY-MM (optional)
      - end: YYYY-MM (optional)
      - period: YYYY-MM,YYYY-MM (optional alternate)
      - duration: float in seconds (default: 20.0, range: [1.0, 60.0])
      - format: string (default: 'wav')
    """
    canon = default_engine.canonical_id(dataset_id)
    if not canon:
        return jsonify({
            "error": "Dataset not found",
            "message": f"Dataset '{dataset_id}' is not recognized.",
            "available_datasets": [
                "surface-temperature",
                "atmospheric-co2",
                "ocean-temperature",
                "sea-ice-extent"
            ]
        }), 404

    # Format validation
    audio_format = request.args.get("format", "wav").lower().strip()
    if audio_format not in ["wav", "audio/wav"]:
        return jsonify({
            "error": "Unsupported audio format",
            "message": f"Format '{audio_format}' is unsupported. Only 'wav' (44.1 kHz PCM stereo) is available."
        }), 400

    # Duration parsing & validation
    duration_arg = request.args.get("duration", "20.0")
    try:
        duration = float(duration_arg)
    except (ValueError, TypeError):
        return jsonify({"error": f"Invalid duration value '{duration_arg}'"}), 400

    if duration <= 0:
        return jsonify({"error": "Duration must be greater than 0 seconds."}), 400
    if duration > 300.0:
        # Clamp excessive durations safely
        duration = 60.0
    else:
        duration = max(1.0, min(60.0, duration))

    # Date range parsing
    start = request.args.get("start")
    end = request.args.get("end")
    period = request.args.get("period")

    if period and (not start or not end):
        p_start, p_end = _parse_period_string(period)
        if p_start and not start:
            start = p_start
        if p_end and not end:
            end = p_end

    if start:
        start = start.strip()
        if not DATE_REGEX.match(start):
            return jsonify({"error": f"Invalid start date format '{start}'. Expected YYYY-MM."}), 400
    if end:
        end = end.strip()
        if not DATE_REGEX.match(end):
            return jsonify({"error": f"Invalid end date format '{end}'. Expected YYYY-MM."}), 400

    if start and end and start > end:
        return jsonify({"error": f"start date '{start}' cannot be after end date '{end}'."}), 400

    try:
        wav_path = default_engine.sonify_dataset(
            dataset_id=canon,
            start=start,
            end=end,
            duration=duration,
            sample_rate=44100
        )
    except Exception as e:
        return jsonify({
            "error": "Sonification synthesis failed",
            "message": str(e)
        }), 500

    response = send_file(
        wav_path,
        mimetype="audio/wav",
        as_attachment=False,
        download_name=f"{canon}_{duration:.0f}s.wav"
    )
    response.headers["Accept-Ranges"] = "bytes"
    response.headers["Cache-Control"] = "public, max-age=604800, immutable"
    return response


@sonification_bp.route("/sonify/orchestra", methods=["GET"])
def sonify_orchestra_endpoint():
    """
    Returns manifest and stem endpoints for all 4 synchronized climate audio layers.
    Query parameters:
      - start: YYYY-MM (optional)
      - end: YYYY-MM (optional)
      - duration: float in seconds (default: 20.0)
    """
    duration_arg = request.args.get("duration", "20.0")
    try:
        duration = float(duration_arg)
        duration = max(1.0, min(60.0, duration))
    except (ValueError, TypeError):
        duration = 20.0

    start = request.args.get("start")
    end = request.args.get("end")

    manifest_data = default_engine.get_orchestra_manifest(start, end, duration)
    return jsonify(manifest_data), 200


@sonification_bp.route("/sonify/differential", methods=["GET"])
def sonify_differential_endpoint():
    """
    Stream 44.1 kHz stereo WAV audio synthesizing the differential signal Delta(t) = B(t) - A(t).
    Query parameters:
      - dataset_id: string (required)
      - periodA: YYYY-MM,YYYY-MM (required)
      - periodB: YYYY-MM,YYYY-MM (required)
      - duration: float in seconds (default: 15.0)
    """
    dataset_id = request.args.get("dataset_id")
    period_a_str = request.args.get("periodA")
    period_b_str = request.args.get("periodB")

    if not dataset_id or not period_a_str or not period_b_str:
        return jsonify({
            "error": "Missing required query parameters",
            "message": "Parameters 'dataset_id', 'periodA', and 'periodB' are required."
        }), 400

    canon = default_engine.canonical_id(dataset_id)
    if not canon:
        return jsonify({"error": f"Unknown dataset '{dataset_id}'"}), 404

    a_start, a_end = _parse_period_string(period_a_str)
    b_start, b_end = _parse_period_string(period_b_str)

    if not a_start or not a_end or not b_start or not b_end:
        return jsonify({
            "error": "Invalid period format",
            "message": "periodA and periodB must be formatted as 'YYYY-MM,YYYY-MM'."
        }), 400

    duration_arg = request.args.get("duration", "15.0")
    try:
        duration = float(duration_arg)
        duration = max(1.0, min(60.0, duration))
    except (ValueError, TypeError):
        duration = 15.0

    try:
        wav_path = default_engine.sonify_differential(
            dataset_id=canon,
            period_a=(a_start, a_end),
            period_b=(b_start, b_end),
            duration=duration,
            sample_rate=44100
        )
    except Exception as e:
        return jsonify({
            "error": "Differential sonification failed",
            "message": str(e)
        }), 500

    response = send_file(
        wav_path,
        mimetype="audio/wav",
        as_attachment=False,
        download_name=f"diff_{canon}_{duration:.0f}s.wav"
    )
    response.headers["Accept-Ranges"] = "bytes"
    response.headers["Cache-Control"] = "public, max-age=604800, immutable"
    return response


@sonification_bp.route("/sonification/explanations", methods=["GET"])
@sonification_bp.route("/sonification/metadata", methods=["GET"])
def sonification_explanations_endpoint():
    """
    Return comprehensive mathematical and musical sonification explanations
    for all active NASA climate variables.
    """
    dataset_id = request.args.get("dataset_id")
    if dataset_id:
        canon = default_engine.canonical_id(dataset_id)
        if canon and canon in SONIFICATION_EXPLANATIONS:
            return jsonify(SONIFICATION_EXPLANATIONS[canon]), 200
        return jsonify({"error": f"No explanation found for '{dataset_id}'"}), 404

    return jsonify({
        "status": "success",
        "description": "EARTHSONIC Mathematical & Musical Sonification Specification",
        "total_layers": len(SONIFICATION_EXPLANATIONS),
        "explanations": SONIFICATION_EXPLANATIONS
    }), 200
